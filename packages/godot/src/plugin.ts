import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  definePlugin,
  type EngineAdapter,
  type EngineInstallation,
  type GameForgePlugin,
} from '@gameforge/core';
import { analyzeGodotProject } from './analyzer.js';
import { detectGodot } from './detect.js';
import { generateGodotProject, MIN_GODOT_VERSION } from './generator.js';
import { applyQuickFix } from './quickfix.js';
import { GodotRunner } from './runner.js';

/** Engine-specific instructions appended to every agent's system prompt. */
export const GODOT_AGENT_GUIDE = `Godot ${MIN_GODOT_VERSION}+ rules (GDScript 2.0):
- Use Godot 4 syntax only: @onready, @export, await (never yield), instantiate(), CharacterBody2D/3D, signal.connect(callable), move_and_slide() without arguments (set velocity first).
- Indent GDScript with tabs, never mix tabs and spaces. Prefer static typing (var speed := 4.0, func f(x: int) -> void).
- Scenes are text .tscn files (format=3). Keep scene changes minimal; prefer building nodes in code when a scene would get complicated.
- Projects generated by GameForge: autoloads GameState (config, inventory, health, signals), AudioManager (play("event")), SaveSystem; tuning values live in data/game_config.json, levels in data/levels/*.json, sound events in audio/sound_events.json, tests in tests/ (run_tests.gd runner, test_*.gd files extending res://tests/test_case.gd).
- Reference files with res:// paths. Input actions must exist in project.godot [input].
- Add or update a test in tests/ when you add game logic.`;

export interface GodotPluginOptions {
  /** Folder containing the GDScript templates (common/, 2d/, 3d/). */
  templatesDir?: string;
  /** Returns the user-configured Godot path (Settings → Godot). */
  configuredExecutable?: () => string | undefined;
  env?: NodeJS.ProcessEnv;
  /** Absolute path where the running game writes preview frames (per project). */
  previewFile?: (root: string) => string | undefined;
}

export function defaultTemplatesDir(): string {
  return fileURLToPath(new URL('../templates', import.meta.url));
}

export function createGodotEngine(
  options: GodotPluginOptions = {},
): EngineAdapter & { runner: GodotRunner; detect(): Promise<EngineInstallation | null> } {
  const templatesDir = options.templatesDir ?? defaultTemplatesDir();
  let cache: { key: string; result: EngineInstallation | null; at: number } | null = null;
  const detect = async () => {
    const configured = options.configuredExecutable?.();
    const key = `${configured ?? ''}|${(options.env ?? process.env).GODOT_PATH ?? ''}`;
    // Cache successful detection; re-check misses after 10 s (user may have just installed Godot).
    if (cache && cache.key === key && (cache.result || Date.now() - cache.at < 10_000))
      return cache.result;
    const result = await detectGodot({
      ...(configured ? { configured } : {}),
      env: options.env ?? process.env,
    });
    cache = { key, result, at: Date.now() };
    return result;
  };
  const runner = new GodotRunner(async () => (await detect())?.executable ?? null);

  return {
    id: 'godot',
    displayName: 'Godot',
    agentGuide: GODOT_AGENT_GUIDE,
    runner,
    detect,
    isProject: async (root) => existsSync(path.join(root, 'project.godot')),
    detectInstallation: detect,
    generate: (plan, workspace, generateOptions) =>
      generateGodotProject(plan, workspace, templatesDir, generateOptions),
    analyze: (workspace, context) => analyzeGodotProject(workspace, context),
    quickFix: (workspace, issue) => applyQuickFix(workspace, issue),
    validate: (root, context) => runner.validate(root, context),
    runTests: (root, context) => runner.runTests(root, context),
    runGame: (root, runOptions) => {
      const previewFile = options.previewFile?.(root);
      return runner.runGame(root, { ...runOptions, ...(previewFile ? { previewFile } : {}) });
    },
  };
}

/** The built-in Godot engine plugin. */
export function createGodotPlugin(options: GodotPluginOptions = {}): GameForgePlugin {
  return definePlugin({
    id: 'godot',
    name: 'Godot',
    version: '0.1.0',
    apiVersion: 1,
    description: `Godot ${MIN_GODOT_VERSION}+ support: project generation, analysis, tests and preview.`,
    activate(context) {
      context.registerEngine(createGodotEngine(options));
    },
  });
}
